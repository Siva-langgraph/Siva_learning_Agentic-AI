CREATE TABLE IF NOT EXISTS products (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku TEXT UNIQUE NOT NULL, name TEXT NOT NULL, category TEXT NOT NULL,
 unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE TABLE IF NOT EXISTS orders (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_date DATE NOT NULL,
 status TEXT NOT NULL CHECK (status IN ('pending','paid','shipped','cancelled')),
 customer_region TEXT NOT NULL,
 total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0)
);
CREATE TABLE IF NOT EXISTS order_items (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id INTEGER NOT NULL REFERENCES orders(id), product_id INTEGER NOT NULL REFERENCES products(id),
 quantity INTEGER NOT NULL CHECK (quantity > 0), unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);
